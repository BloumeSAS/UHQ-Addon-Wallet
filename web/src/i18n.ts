export function useT() {
  const { lang } = useAddon();
  return (key: string) => I18N[lang]?.[key] ?? I18N['fr'][key] ?? key;
}

export function fmt(value: number, currency = 'EUR', lang = 'fr') {
  return new Intl.NumberFormat(lang === 'fr' ? 'fr-FR' : 'en-US', {
    style: 'currency',
    currency,
  }).format(value);
}
